import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { openDatabase,Repository } from '../src/database.js';
import { validateSnapshot } from '../src/catalog.js';
import { selectLfxUsdRate } from '../src/fx.js';
import { OrderService } from '../src/orders.js';

test('manual order snapshots, ownership, idempotency and internal messages are isolated',async()=>{
 const db=await openDatabase('memory:');const catalog=new Repository(db);await catalog.init();
 try {
  const seed=JSON.parse(await readFile(new URL('../jorjee-game-packages.json',import.meta.url),'utf8'));
  await catalog.save(validateSnapshot(seed.games),'2026-11-18T08:00:00Z','live');
  await catalog.saveFxRate(selectLfxUsdRate([{Time:'15:00-16:00',Label:'USD',Price:'22688.45'}]),'2026-11-18T08:00:00Z');
  const service=new OrderService(db,()=>catalog.latestFxRate());await service.init();
  const ff=(await catalog.packages('free-fire',false))[0];
  const ml=(await catalog.packages('mobile-legends-bang-bang',false))[0];
  await assert.rejects(service.publish({name:'bad',game_id:'mobile-legends-bang-bang',zone:'unspecified',offer_ids:[ml.id],markup_bps:1000}),/zone/i);
  const product=await service.publish({name:'Free Fire test',game_id:'free-fire',zone:'th',offer_ids:[ff.id],markup_bps:1000});
  const shop=await service.products();assert.equal(shop[0].price_usd,'0.39');assert.equal('source_id' in shop[0],false);
  const token='a'.repeat(43);const args={product_id:product.id,player:{UID:'123456'},token,idempotency_key:'request-1234567890'};
  const order=await service.create(args);
  assert.deepEqual(await service.create(args),order);
  await assert.rejects(service.create({...args,player:{UID:'different'}}),/conflict/i);
  await assert.rejects(service.read(order.id,'b'.repeat(43)),/not found/i);
  assert.equal(JSON.stringify(order).includes(ff.id),false);
  await service.message(order.id,token,'hello');
  await service.adminMessage(order.id,'private supplier details','internal','test-note');
  await service.adminMessage(order.id,'hello customer','public','test-reply');
  const publicOrder=await service.read(order.id,token);
  assert.equal(publicOrder.messages.length,2);assert.equal(JSON.stringify(publicOrder).includes('private supplier'),false);
  await assert.rejects(service.action(order.id,'complete','done-before-payment'),/transition|payment/i);
  await assert.rejects(service.action(order.id,'reopen','reopen-before-payment'),/transition|payment/i);
  await assert.rejects(service.action(order.id,'accept','accept-before-payment'),/transition|payment/i);
  await assert.rejects(service.action(order.id,'start','start-before-payment'),/transition|payment/i);
  await service.receipt(order.id,token,{id:'receipt-1',path:'private/test.png',mime:'image/png',size:100});
  assert.equal((await service.adminRead(order.id)).receipts[0].path,'private/test.png');
  await service.action(order.id,'approve','approve-1');
  assert.equal((await service.read(order.id,token)).status,'paid');
  await assert.rejects(service.action(order.id,'start','start-before-accept'),/transition|payment/i);
  await assert.rejects(service.action(order.id,'complete','done-before-start'),/transition|payment/i);
  await service.action(order.id,'accept','accept-1');
  assert.equal((await service.read(order.id,token)).status,'accepted');
  await service.action(order.id,'accept','accept-1');
  await service.action(order.id,'start','start-1');
  assert.equal((await service.read(order.id,token)).status,'processing');
  await service.action(order.id,'complete','complete-1');
  await service.action(order.id,'complete','complete-1');
  assert.equal((await service.read(order.id,token)).status,'completed');
  await service.action(order.id,'reopen','reopen-1');
  await service.action(order.id,'reopen','reopen-1');
  assert.equal((await service.read(order.id,token)).status,'processing');
  assert.equal((await service.adminRead(order.id)).payment_verified,true);
  await assert.rejects(service.action(order.id,'reopen','reopen-already-processing'),/transition|payment/i);
  await service.action(order.id,'complete','complete-after-reopen');
  await service.action(order.id,'refund','refund-after-reopen');
  await assert.rejects(service.action(order.id,'reopen','reopen-refunded'),/transition|payment/i);
  const afterActions=await service.read(order.id,token);
  assert.equal(afterActions.messages.some((m:any)=>m.sender==='system'),false,'Order state changes must not become customer chat messages');
  assert.ok((await service.pending()).length>=3);
 }finally{await db.close();}
});
